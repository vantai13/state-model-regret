def read(path):
    return json.loads((ROOT / path).read_text())


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git(*args):
    return subprocess.check_output(['git', '-C', str(ROOT), *args], text=True).strip()


def check_index(base):
    index = read(base + '/output_hashes.json')
    for name, expected in index.items():
        assert digest(ROOT / base / name) == expected, (base, name)
    return len(index)


def anchors(text):
    result, counts = set(), {}
    for line in text.splitlines():
        if not re.match(r'^#{1,6} ', line):
            continue
        slug = re.sub(r'[^\w\- ]', '', line.lstrip('#').strip().lower()).replace(' ', '-')
        count = counts.get(slug, 0)
        counts[slug] = count + 1
        result.add(slug + (f'-{count}' if count else ''))
    return result


def check_links(paths):
    checked, errors = 0, []
    for rel in paths:
        path = ROOT / rel
        for target in re.findall(r'\]\(([^)]+)\)', path.read_text()):
            if re.match(r'^[a-zA-Z]+:', target):
                continue
            target = unquote(target.strip('<>'))
            filename, _, anchor = target.partition('#')
            destination = (path.parent / filename).resolve() if filename else path
            if not destination.exists():
                errors.append(f'{rel}: missing {target}')
            elif anchor and destination.suffix == '.md' and anchor not in anchors(destination.read_text()):
                errors.append(f'{rel}: missing anchor {target}')
            checked += 1
    assert not errors, '\n'.join(errors)
    return checked


