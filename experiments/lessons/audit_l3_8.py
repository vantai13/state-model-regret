    assert manifest['open_ids'] == decision['open_ids'] == ids
    assert manifest['sealed_ids'] == ['R09', 'R10'] and manifest['one_shot'] is True
    raw = ROOT / 'results/A05_test/20261028_01/raw'
    assert {p.name for p in raw.glob('*.json')} == {f'{cid}_m{ref}.json' for cid in ids for ref in (1, 2)}
    dc = manifest['decision']['decision_commit']
    stages = [frozen[k] for k in ['author_decision_commit', 'prereg_commit', 'theta_commit', 'prediction_commit', 'freeze_commit']]
    stages += [decision['runner_commit'], dc, 'e719157c2f55a5cff2163bb73ef09a31a3483f7e']
    for before, after in zip(stages, stages[1:]):
        assert before != after
        subprocess.run(['git', '-C', str(ROOT), 'merge-base', '--is-ancestor', before, after], check=True)
    committed_at = datetime.fromisoformat(git('show', '-s', '--format=%cI', dc))
    assert committed_at < datetime.fromisoformat(manifest['start_utc']) < datetime.fromisoformat(status['end_utc'])
    checks = {'frozen_chain': 'PASS', 'tests': xml, 'output_hash_counts': hash_counts,
              'A05_T_registered_source_hashes': len(decision['source_sha256']),
              'A01_final_dt_s': a01['final_dt_s'], 'A04_bounded_levels': 92,
              'A04_pairs': 46, 'A05_T_bounded_levels': 20, 'A05_T_pairs': 10,
              'chronology': stages, 'no_sealed_outcomes_in_saved_run': ['R09', 'R10']}
    rescore = subprocess.run([sys.executable, '-m', 'experiments.A05_test.rescore',
                             'results/A05_test/20261028_01'], cwd=ROOT, text=True, capture_output=True)
    (OUT / 'rescore.log').write_text(rescore.stdout + rescore.stderr)
    assert rescore.returncode == 0, rescore.stderr
    checks['independent_rescore'] = json.loads(rescore.stdout)
    assert checks['independent_rescore']['agreement'] == 'PASS'
    verdict = read('results/A05_test/20261028_01/verdict.json')['grades']
    outcome = {'PC4_primary': verdict['primary_verdict'],
               'PC4_extrapolation': verdict['PC4']['extrapolation']['verdict'],
               'weak_interpolation': verdict['PC4']['weak_interpolation']['verdict'],
               'K5': verdict['K5']['full_rule_verdict'], 'C1': verdict['C1']['heldout']['verdict']}
    assert list(outcome.values()) == ['WEAKEN', 'FALSIFY', 'DO_NOT_OPEN', 'DOES_NOT_STAND', 'STANDS']
    checks['outcomes_unchanged'] = outcome
    for key, phrase in [('PC4_primary', 'WEAKEN'), ('PC4_extrapolation', 'FALSIFY')]:
        assert outcome[key] == phrase
    checks['numeric_metrics'] = {group: {key: [float(Fraction(x) * 100) for x in verdict['PC4'][group][key]]
                                                 for key in ['MAE0', 'MAE1', 'd_interval']}
                                 for group in ['interpolation', 'extrapolation']}
    ownership = read('notes/phases/PHASE_3_author_decision.json')
    assert ownership['P0_V10'] == ownership['L8'] == 'OPEN'
    assert ownership['phase4_execution'] == 'HOLD' and ownership['phase4_study'] == 'ALLOWED'
    pending = []
