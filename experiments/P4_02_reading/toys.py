"""Doan Van Tai — supplied L4.2 toys, AI implementation, no plant engine.

Costs use arbitrary teaching units. Dhat is chosen, not generated by a queue.
The non-contract tie option exists only to demonstrate a counterfactual defect.
"""
from fractions import Fraction as F


TOYS = {
    'T-A': ((F(-1), F(6, 5)), (F(-1), F(6, 5))),
    'T-AB': ((F(1), F(1)), (F(-3), F(1))),
    "T-C'": ((F(1), F(1)), (F(-3), F(4))),
}
# Additional worked example by AI, not an author exercise/attestation.
TOY_B = ((F(1), F(1)), (F(-1), F(-1)))


def cells(d, dh, tie_stay=True, js=F(10)):
    """Two equiprobable states under a single uninformative observation."""
    d, dh, js = tuple(map(F, d)), tuple(map(F, dh)), F(js)
    if len(d) != 2 or len(dh) != 2:
        raise ValueError('exactly two states required')
    p = (F(1, 2), F(1, 2))
    choose = lambda z: int(z < 0) if tie_stay else int(z <= 0)
    g, gh = sum(p[i]*d[i] for i in range(2)), sum(p[i]*dh[i] for i in range(2))
    a00 = (choose(gh),) * 2
    a01 = (choose(g),) * 2
    a10 = tuple(choose(z) for z in dh)
    a11 = tuple(choose(z) for z in d)
    cost = lambda actions: sum(p[i]*(js + actions[i]*d[i]) for i in range(2))
    l00, l01, l10, l11 = map(cost, (a00, a01, a10, a11))
    return dict(L00=l00, L01=l01, L10=l10, L11=l11,
                GS=l00-l10, GM=l00-l01, GSM=l00-l11,
                Gam=l10+l01-l00-l11, GS_M1=l01-l11, GM_S1=l10-l11, Cref=l11,
                P=sum(p[i]*max(d[i], 0) for i in range(2)),
                N=sum(p[i]*max(-d[i], 0) for i in range(2)),
                g=g, gh=gh, a00=a00, a01=a01, a10=a10, a11=a11)


def cls(c):
    """Archived reading rule applied with exact fractions, never a new card."""
    if c['Cref'] <= 0:
        raise ValueError('positive Cref required for class percentages')
    gs, gm, gsm, gam = (100*c[k]/c['Cref'] for k in ('GS', 'GM', 'GSM', 'Gam'))
    if gs <= -1:
        return 'C'
    if gs >= 1:
        return 'A' if gm < 1 else 'AB'
    if gm >= 1:
        return 'B'
    if gsm >= 1 and gam >= max(gs, gm):
        return 'J'
    return 'D'


def endpoint_cost(net_rates, dt, q0=F(0), buffer=None):
    """Small exact recurrence fixture, not the project's numerical engine."""
    dt, q = F(dt), F(q0)
    if dt <= 0 or q < 0:
        raise ValueError('positive dt and nonnegative q0 required')
    trajectory, total = [q], F(0)
    for rate in net_rates:
        q = max(F(0), q + F(rate)*dt)
        if buffer is not None:
            q = min(F(buffer), q)
        trajectory.append(q)
        total += dt*q  # endpoint convention; includes last slot, excludes q0
    return tuple(trajectory), total


def exact_toy_results():
    records=[]
    for name, (d, dh) in [*TOYS.items(), ('T-B (AI example)', TOY_B)]:
        c = cells(d, dh)
        records.append(dict(toy=name, delta=list(map(str, d)), delta_hat=list(map(str, dh)),
                            values={k: str(v) if isinstance(v, F) else list(v) for k,v in c.items()},
                            label=cls(c), unit='arbitrary_toy_cost_unit', queue_engine=False))
    return records
